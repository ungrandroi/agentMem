"""Single-action JSON contract and explicit recoverable submission errors."""
import json
import uuid

class ActionProtocolError(ValueError):
    def __init__(self,message,raw):
        super().__init__(message);self.raw=raw

INSTRUCTION=('Output exactly one JSON object with keys "name" and "args" for one available tool. '
             'Do not output an array, multiple objects, XML, Markdown or additional prose. '
             'There is no finish action. Continue choosing one operation until run_tests confirms success or the environment exhausts the budget. '
             'A small remaining budget does not mean the budget is exhausted. '
             'If the host rejects a response, no requested operation executes. '
             'The host records the rejected submission as __action_submission__ with a tool error; '
             'correct it by selecting exactly one operation on the next decision.')

def action_schema(tools):
    choices=[{'type':'object','properties':{'name':{'type':'string','enum':[t['function']['name']]},
                'args':t['function']['parameters']},'required':['name','args'],'additionalProperties':False} for t in tools]
    return {'oneOf':choices}

def check(value,schema):
    kind=schema.get('type')
    if kind=='object':
        if type(value) is not dict:raise ValueError('Expected one object')
        props=schema.get('properties',{})
        if set(schema.get('required',[]))-set(value):raise ValueError('Missing required fields')
        if schema.get('additionalProperties') is False and set(value)-set(props):raise ValueError('Extra fields are not allowed')
        for key,item in value.items():
            if key in props:check(item,props[key])
    elif kind=='string':
        if type(value) is not str or len(value)<schema.get('minLength',0):raise ValueError('Expected a string of the required length')
    elif kind=='integer':
        if type(value) is not int or not schema.get('minimum',float('-inf'))<=value<=schema.get('maximum',float('inf')):raise ValueError('Integer outside bounds')
    elif kind=='boolean' and type(value) is not bool:raise ValueError('Expected boolean')
    if 'enum' in schema and value not in schema['enum']:raise ValueError('Value is not an available choice')

def parse_action(raw,tools):
    try:
        def unique(pairs):
            d={}
            for k,v in pairs:
                if k in d:raise ValueError('Duplicate JSON key')
                d[k]=v
            return d
        value=json.loads(raw,object_pairs_hook=unique)
        if type(value) is not dict or type(value.get('name')) is not str:raise ValueError('Return one {name,args} object')
        schema=next((s for s in action_schema(tools)['oneOf'] if s['properties']['name']['enum']==[value['name']]),None)
        if schema is None:raise ValueError('Unknown operation')
        check(value,schema)
        return {'role':'assistant','content':None,'tool_calls':[{'id':'action_'+uuid.uuid4().hex[:12],
                'type':'function','function':{'name':value['name'],'arguments':json.dumps(value['args'])}}]}
    except (ValueError,TypeError) as exc:raise ActionProtocolError(str(exc),raw) from exc


def rejection_exchange(error,public,index):
    # This is explicitly HOST-normalized, not a tool call claimed to be generated by the model.
    call_id='rejected_submission_'+str(index)
    return [{'role':'assistant','content':None,'tool_calls':[{'id':call_id,'type':'function',
        'function':{'name':'__action_submission__','arguments':json.dumps({'raw_output':error.raw})}}]},
        {'role':'tool','tool_call_id':call_id,'content':json.dumps(public)}]


def parse_xml_action(raw,tools):
    """Legacy Q8 XML transport shares the same recoverable error semantics."""
    import re
    if '<tool_call>' not in raw:return {'role':'assistant','content':raw}
    try:
        calls=re.findall(r'<tool_call>\s*<function=([^>]+)>(.*?)</function>\s*</tool_call>',raw,re.S)
        if len(calls)!=1 or raw.count('<tool_call>')!=1:raise ValueError('Return exactly one complete tool call')
        name,body=calls[0]
        schema=next((t['function']['parameters'] for t in tools if t['function']['name']==name),None)
        if schema is None:raise ValueError('Unknown tool')
        pattern=r'<parameter=([^>]+)>\n?(.*?)\n?</parameter>'
        if re.sub(pattern,'',body,flags=re.S).strip():raise ValueError('Malformed parameters')
        args={}
        for key,value in re.findall(pattern,body,re.S):
            if key in args or key not in schema['properties']:raise ValueError('Invalid parameter')
            value=value.strip('\n');args[key]=value if schema['properties'][key]['type']=='string' else json.loads(value)
        check(args,schema)
        return parse_action(json.dumps({'name':name,'args':args}),tools)
    except (ValueError,TypeError) as exc:raise ActionProtocolError(str(exc),raw) from exc
